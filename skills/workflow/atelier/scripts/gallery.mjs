#!/usr/bin/env node
// gallery.mjs — builds scripts/fixtures/comments/README.md: atelier's sticky PR comment in every state,
// rendered by state.mjs from the fixtures beside it, plus every pre-rendered card and the mascot moods.
//
//   node gallery.mjs              write the README
//   node gallery.mjs --self-test  exit 1 when the README is stale or a reachable state has no card (L1 G114)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { allKeys, altText } from "./card.mjs";
import { isMain, makeTester } from "./lib.mjs";
import { MOODS } from "./mascot.mjs";
import { missingCards } from "./render-cards.mjs";
import { render } from "./state.mjs";

const DIR = join(dirname(fileURLToPath(import.meta.url)), "fixtures", "comments");
const OUT = join(DIR, "README.md");
const ASSETS = "../../../assets";
const CARDS = `${ASSETS}/cards`;
const MASCOT = "../../../assets/mascot";

// Gallery order and what each state shows. Each name is a `<name>.json` state in this folder.
const STATES = [
	["built", "Built", "aw opened the draft PR and its companions ran; Ready runs next."],
	["existing-pr-ready", "Ready (existing PR, limited preflight)", "Build skipped for an existing PR, Ready passed with green CI evidence, and a preflight gap shows as a heads-up."],
	["build-held", "Held at Build", "A required companion did not run, so Build holds and names it."],
	["build-failed", "Build failed, two problems", "Two problems stopped Build; each gets its own line, and the limited preflight stays in Run details because it did not cause the stop."],
	["build-refused", "Build refused", "The early merge gate refused twice, so Build records `refuse` and names the gate's line."],
	["ready-held", "Held at Ready", "CI never ran on the draft, so Ready holds instead of passing on skipped checks."],
	["ready-failed", "Ready failed", "CI stayed red after the one fix attempt."],
	["merge-refused", "Merge refused", "The merge gate refused a user-visible diff without a flag contract."],
	["merged", "Merged, delivering", "Squash-merged; Deliver is reading `main`'s pipeline for the merge commit."],
	["delivered", "Merged and delivered", "`main` went green for the merge commit."],
	["deliver-reverted", "Deliver failed and reverted", "`main` stayed red after one fix, so the merge was reverted; a human takes it from here."],
];

const picture = (key, width) =>
	`<picture><source media="(prefers-color-scheme: dark)" srcset="${CARDS}/${key}-dark.png"><img src="${CARDS}/${key}-light.png" width="${width}" alt="${altText(key.split("-"))}"></picture>`;

export function build() {
	const parts = [
		"<!-- Generated by skills/workflow/atelier/scripts/gallery.mjs — edit a fixture or the script, then rerun it. -->",
		"",
		"# atelier comment gallery",
		"",
		"The sticky comment `atelier` keeps on a PR, in every state, rendered by [`state.mjs`](../../state.mjs) from the `*.json` state beside it.",
		"Each comment opens with a status card picked from [`assets/cards/`](../../../assets/cards), pre-rendered by [`render-cards.mjs`](../../render-cards.mjs) in a light and a dark version; GitHub shows the one matching your theme.",
		"The layout contract is [`rules/state.md`](../../../rules/state.md).",
		"",
		"## Changing a state or the art",
		"",
		"1. Edit `<name>.json` here, or [`card.mjs`](../../card.mjs) / [`mascot.mjs`](../../mascot.mjs) for the art.",
		"2. After an art change, re-render the cards: `node skills/workflow/atelier/scripts/render-cards.mjs` (needs Chrome).",
		"3. Rebuild this file: `node skills/workflow/atelier/scripts/gallery.mjs`; L1 `G114` runs its `--self-test`, which fails on a stale README or a missing card.",
		"",
		"## States",
		"",
		...STATES.map(([name, title]) => `- [${title}](#${title.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-")})`),
		"- [Every card](#every-card)",
		"- [Mascot](#mascot)",
		"",
	];
	for (const [name, title, what] of STATES) {
		const state = JSON.parse(readFileSync(join(DIR, `${name}.json`), "utf8"));
		const body = render(state, { assetBase: ASSETS });
		parts.push(`## ${title}`, "", what, "", `State: [\`${name}.json\`](${name}.json)`, "", "> [!NOTE]", "> Rendered as GitHub shows it; times read as a fixed date here and as \"2 minutes ago\" on a PR.", "", body, "", "<details>", "<summary>Markdown source</summary>", "", "````markdown", render(state), "````", "", "</details>", "");
	}
	parts.push("## Every card", "", `All ${allKeys().length} reachable states; the file name is \`<build>-<ready>-<merge>-<deliver>-<theme>.png\`.`, "");
	for (const key of allKeys()) parts.push(`**\`${key}\`**`, "", picture(key, 560), "");
	parts.push("## Mascot", "", "One mood per verdict; his brush tip takes the verdict's colour.", "", `| ${Object.keys(MOODS).join(" | ")} |`, `| ${Object.keys(MOODS).map(() => ":-:").join(" | ")} |`, `| ${Object.keys(MOODS).map((m) => `<img src="${MASCOT}/${m}.svg" width="96" alt="${m}">`).join(" | ")} |`, "");
	return parts.join("\n");
}

function selfTest() {
	const { t, done } = makeTester("gallery");
	t("the gallery README is current (run node gallery.mjs)", readFileSync(OUT, "utf8") === build());
	const missing = missingCards();
	t("every reachable state has a light and a dark card (run node render-cards.mjs)", missing.length === 0, missing.join(", "));
	return done();
}

if (isMain(import.meta.url)) {
	if (process.argv[2] === "--self-test") process.exit(selfTest());
	writeFileSync(OUT, build());
	console.log(`wrote ${OUT}`);
}
